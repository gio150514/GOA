sales = [45, 50, 62, 40, 55, 90, 105]

# ორშაბათის გაყიდვები (პირველი ელემენტი)
print(sales[0])

# ოთხშაბათის გაყიდვები (მესამე ელემენტი)
print(sales[2])

# კვირის გაყიდვები (ბოლო ელემენტი -1 ინდექსით)
print(sales[-1])

# ხუთშაბათის გაყიდვების შეცვლა
sales[3] = 48

# მთლიანი სიის დაბეჭდვა
print(sales)